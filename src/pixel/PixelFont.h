inline const Glyph* findGlyph (char c)
{
    const char upper = (char) std::toupper ((unsigned char) c);

    for (const auto& glyph : fontTable())
        if (glyph.c == upper)
            return &glyph;

    return nullptr;
}

inline int textWidth (const juce::String& text, int scale = 1)
{
    return text.isEmpty() ? 0 : (text.length() * kAdvance - 1) * scale;
}

/** Draws text on the integer pixel grid; every lit cell is a filled rectangle. */
inline void drawText (juce::Graphics& g, const juce::String& text,
                      int x, int y, juce::Colour colour, int scale = 1)
{
    g.setColour (colour);
    int cursor = x;

    for (int i = 0; i < text.length(); ++i)
    {
        if (const Glyph* glyph = findGlyph (text[i]))
        {
            for (int row = 0; row < kGlyphH; ++row)
            {
                const char* cells = glyph->rows[row];

                for (int col = 0; col < kGlyphW; ++col)
                    if (cells[col] == '#')
                        g.fillRect (cursor + col * scale, y + row * scale, scale, scale);
            }
        }

        cursor += kAdvance * scale;
    }
}

inline void drawTextCentred (juce::Graphics& g, const juce::String& text,
                             juce::Rectangle<int> area, juce::Colour colour, int scale = 1)
{
    const int w = textWidth (text, scale);
    const int h = kGlyphH * scale;
    drawText (g, text,
              area.getX() + (area.getWidth() - w) / 2,
              area.getY() + (area.getHeight() - h) / 2,
              colour, scale);
}

inline void drawTextRight (juce::Graphics& g, const juce::String& text,
                           int rightX, int y, juce::Colour colour, int scale = 1)
{
    drawText (g, text, rightX - textWidth (text, scale), y, colour, scale);
}
